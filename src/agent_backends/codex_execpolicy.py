"""Codex execpolicy guard: hard-forbid the real-money exchange scripts (dv-4fc2).

Stopgap until Codex gets a real Approve/Deny bridge (dv-bf0c). Claude turns
confirm these scripts via the PreToolUse gate; Codex runs devops with
``danger-full-access`` and approval ``never``, so nothing asks. Here we make
Codex refuse them outright, so trades only go through Claude.

Mechanism: codex loads every ``$CODEX_HOME/rules/*.rules`` file at startup
(user layer; ``codex exec --ignore-rules`` would skip it -- we never pass that).
We write one bot-owned file there before every turn. ``decision="forbidden"``
rejects the command regardless of sandbox/approval mode.

The script list comes from ``src.security.destructive`` (one source of truth).

Limits -- execpolicy is **exact-token prefix matching**:
* codex splits a plain ``bash -lc "a && b | c"`` script into its commands and
  checks each, so ``cd x && node perp.js`` is caught. A script it can't parse
  as plain words (``$(...)``, ``$VAR`` paths, redirections, heredocs) is
  checked as the single ``bash -lc <script>`` argv and slips through.
* Only the listed spellings of the script path match (bare, ``./``, dir-
  relative, ``~/tools/...``, absolute). ``node ../fetchcrypto/perp.js``,
  ``node -e 0 perp.js`` or ``node --flag perp.js`` do not.
* Anything that spawns node itself (python subprocess, a wrapper script,
  ``npm run``, ``xargs``) is invisible to it.
It's a speed bump against casual/injected use, not a sandbox.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import List, Optional

import structlog

from src.security.destructive import EXCHANGE_TOOL_DIRS, MONEY_SCRIPT_NAMES

logger = structlog.get_logger()

RULES_FILENAME = "devvy-money-guard.rules"

# The program token as the model typically writes it, plus the absolute paths
# codex may see after shell parsing.
NODE_PROGRAMS = (
    "node",
    "nodejs",
    "/usr/bin/node",
    "/bin/node",
    "/usr/local/bin/node",
    "/usr/bin/nodejs",
    "/bin/nodejs",
)

JUSTIFICATION = (
    "Real-money exchange script: blocked on the Codex backend (no owner "
    "Approve/Deny gate here). Ask the owner to run it via the Claude backend."
)


def default_tools_root() -> Path:
    return Path.home() / "tools"


def script_path_variants(tools_root: Optional[Path] = None) -> List[str]:
    """Every spelling of each money script's path that we forbid."""
    root = tools_root or default_tools_root()
    out: List[str] = []
    for name in MONEY_SCRIPT_NAMES:
        script = f"{name}.js"
        forms = [script, f"./{script}"]
        for d in EXCHANGE_TOOL_DIRS:
            forms += [
                f"{d}/{script}",
                f"./{d}/{script}",
                f"tools/{d}/{script}",
                f"~/tools/{d}/{script}",
                f"{root}/{d}/{script}",
            ]
        for f in forms:
            if f not in out:
                out.append(f)
    return out


def render_rules(tools_root: Optional[Path] = None) -> str:
    """The Starlark rules file text. ``match``/``not_match`` are self-tests
    codex validates when it loads the file."""
    root = tools_root or default_tools_root()
    variants = script_path_variants(root)
    first = f"{MONEY_SCRIPT_NAMES[0]}.js"
    lines = [
        "# Generated by devvy_bot (src/agent_backends/codex_execpolicy.py).",
        "# Rewritten before every Codex turn -- edits here are overwritten.",
        "",
    ]
    for program in NODE_PROGRAMS:
        lines += [
            "prefix_rule(",
            f"    pattern = [{json.dumps(program)}, {json.dumps(variants)}],",
            '    decision = "forbidden",',
            f"    justification = {json.dumps(JUSTIFICATION)},",
            f"    match = [[{json.dumps(program)}, {json.dumps(first)}]],",
            f'    not_match = [[{json.dumps(program)}, "index.js", "--quick"]],',
            ")",
            "",
        ]
    return "\n".join(lines)


def rules_path(home: Path) -> Path:
    return home / "rules" / RULES_FILENAME


def ensure_rules(home: Path, tools_root: Optional[Path] = None) -> Path:
    """Write the rules file under ``home/rules`` if missing or stale.

    Raises on failure: callers must not start a Codex turn without the guard.
    """
    path = rules_path(home)
    text = render_rules(tools_root)
    try:
        if path.read_text(encoding="utf-8") == text:
            return path
    except FileNotFoundError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(f".tmp{os.getpid()}")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)
    logger.info("Wrote Codex money-script execpolicy guard", path=str(path))
    return path
