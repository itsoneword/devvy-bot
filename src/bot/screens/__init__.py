"""Bot screens as the phone shows them (dv-4cd8).

A *screen* is one bot message: its text and inline keyboard. Review used to
check code against the plan and tests asserted callback_data, so nobody saw
"Clau…nnet / Clau…pus / Clau…able" until the owner did (dv-d63d). This
package is the mechanical half of the UI gate:

* ``model``    — ``Screen`` / ``Button``, from a markup or a frozen JSON file;
* ``metrics``  — phone geometry and Telegram's middle-ellipsis truncation,
  measured with a vendored width table (``widths.json``, generated by
  ``scripts/screens_widths.py``; no Pillow);
* ``checks``   — ``check(screen)`` → violations: truncated, duplicate,
  exclusive, row_width, too_long, slow;
* ``capture``  — run a handler with a fake ``reply_text`` and time it;
* ``registry`` — every screen the gate builds, with its goal and, for a
  screen that fails today, the ticket that fixes it (``known_bad``);
* ``render``   — ``layout(screen)`` (pure) and ``render(screen)`` → a PNG at
  2x phone width, flagged buttons outlined in red (Pillow, imported lazily);
* ``cli``      — ``scripts/screens check`` / ``render --out DIR [--base REV]``.

``fixtures/`` holds frozen screens of shipped mistakes (7fca8f0's /model,
dv-6104's menu): they must keep failing.
"""
