"""`.env.example` must match `src/config/settings.py` (dv-8e04).

The example file is generated by ``scripts/gen_env_example.py``. This test is
the drift guard: it fails on the commit that adds a setting without
regenerating, rather than months later when someone copies the example and
wonders why a documented variable does nothing.

It also checks the two properties ``scripts/render_env.py`` depends on, since
the installer seeds every ``.env`` from this file.
"""

import importlib.util
import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / "scripts" / "gen_env_example.py"
ENV_EXAMPLE = REPO_ROOT / ".env.example"


def _load_generator():
    spec = importlib.util.spec_from_file_location("gen_env_example", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


gen = _load_generator()


def _assignments(text: str) -> dict:
    """Uncommented ``KEY=VALUE`` lines, as dotenv would read them."""
    out = {}
    for line in text.splitlines():
        if line.lstrip().startswith("#"):
            continue
        match = re.match(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$", line)
        if match:
            out[match.group(1)] = match.group(2).strip()
    return out


def _documented(text: str) -> set:
    """Every key the file mentions, commented out or not."""
    return set(re.findall(r"^(?:#\s*)?([A-Z][A-Z0-9_]*)\s*=", text, flags=re.MULTILINE))


class TestGeneratedFileIsCurrent:
    def test_env_example_matches_settings(self):
        expected = gen.generate()
        actual = ENV_EXAMPLE.read_text(encoding="utf-8")
        assert actual == expected, (
            ".env.example is out of date with src/config/settings.py. "
            "Run `make env-example` and commit the result."
        )

    def test_check_mode_passes(self):
        assert gen.main(["--check"]) == 0


class TestEveryFieldIsDocumented:
    def test_all_settings_fields_present(self):
        from src.config.settings import Settings

        documented = _documented(ENV_EXAMPLE.read_text(encoding="utf-8"))
        missing = [
            name.upper()
            for name in Settings.model_fields
            if name.upper() not in documented
        ]
        assert not missing, f"undocumented settings: {missing}"


class TestInstallerContract:
    """Properties `scripts/render_env.py` and `install.sh` rely on."""

    def test_only_installer_facing_keys_are_live(self):
        # An uncommented line here is pinned into every generated .env, which
        # would freeze today's defaults for good. Only the keys the installer
        # fills in (or a human must) may be live.
        live = set(_assignments(ENV_EXAMPLE.read_text(encoding="utf-8")))
        assert live == gen.ACTIVE

    def test_live_values_are_empty(self):
        # render_env.py blanks placeholder values; there should be nothing to
        # blank, and nothing that would start the bot with a stranger's config.
        values = _assignments(ENV_EXAMPLE.read_text(encoding="utf-8"))
        assert all(v == "" for v in values.values()), values

    def test_no_secret_shaped_values(self):
        text = ENV_EXAMPLE.read_text(encoding="utf-8")
        for pattern in (r"sk-ant-[A-Za-z0-9]", r"\d{8,}:[A-Za-z0-9_-]{30,}"):
            assert not re.search(pattern, text), f"{pattern} matched .env.example"


class TestGeneratorInternals:
    @pytest.mark.parametrize(
        "comment,expected",
        [
            ("Rate limiting", True),
            ("Security relaxation (for trusted environments)", True),
            # Sentences and long prose are explanation, not section headings.
            ("Context healing: re-inject lost assistant prose from SQLite.", False),
            ("NOTE: When changing this list, also update docs/tools.md", False),
            ("", False),
        ],
    )
    def test_heading_detection(self, comment, expected):
        assert gen._is_heading(comment) is expected

    def test_sections_follow_settings_source(self):
        source = (REPO_ROOT / "src" / "config" / "settings.py").read_text()
        sections = gen.parse_sections(source)
        assert sections["telegram_bot_token"] == "Bot settings"
        assert sections["allowed_users"] == "Security"
        assert sections["rate_limit_requests"] == "Rate limiting"
        assert sections["log_level"] == "Monitoring"

    def test_defaults_render_as_env_values(self):
        assert gen.render_default(True) == "true"
        assert gen.render_default(False) == "false"
        assert gen.render_default(None) == ""
        assert gen.render_default(["a", "b"]) == "a,b"
        assert gen.render_default({1: 2.0}) == "1:2.0"
        assert gen.render_default(Path("data/bot.db")) == "data/bot.db"
