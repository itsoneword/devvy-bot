#!/usr/bin/env python3
"""Instantiate profiles from ``data/templates/profiles/`` (dv-4e29, dv-7d92).

``config/profiles.yaml`` is per-machine deployment config, not source: it is
gitignored, and a fresh clone has none. This builds one out of the shipped
templates, so a new install gets ``devops`` + ``general`` without anyone
hand-editing YAML, and the rest of the templates stay available to add later.

Standard library only, on purpose. ``install.sh`` runs this *before*
``poetry install``, so it cannot import PyYAML or anything from ``src/``.
That is also why fragments are assembled as text rather than parsed: each
``profile.yaml`` is a one-item YAML list that only needs ``@SLUG@`` substituted
and two spaces of indent to sit under ``profiles:``. The real parse and the
real validation happen at boot, in ``load_profile_registry``.

Usage:
    install_profiles.py --list
    install_profiles.py --install devops,general      # create the file
    install_profiles.py --add coach                   # append one, idempotent
    install_profiles.py --add pm --slug work          # different target slug
    install_profiles.py --install devops,general --dry-run
"""

from __future__ import annotations

import argparse
import re
import sys
import time
from pathlib import Path
from typing import List, Optional, Sequence

REPO_ROOT = Path(__file__).resolve().parent.parent
TEMPLATES_DIR = REPO_ROOT / "data" / "templates" / "profiles"
DEFAULT_CONFIG = REPO_ROOT / "config" / "profiles.yaml"

# The two that ship active (dv-1a55 D4). Everything else is a template only.
DEFAULT_PROFILES = ("devops", "general")

SLUG_RE = re.compile(r"^[a-z][a-z0-9_-]*$")
ENTRY_SLUG_RE = re.compile(r"""^\s*-\s*slug:\s*["']?([A-Za-z0-9_-]+)["']?""")

HEADER = """\
# Profile registry for THIS machine -- generated by scripts/install_profiles.py.
#
# Not source: this file is gitignored because every deployment wants different
# profiles. Regenerate or extend it with
#
#   python3 scripts/install_profiles.py --list
#   python3 scripts/install_profiles.py --add coach
#
# and restart the bot afterwards -- PROFILES_CONFIG_PATH is read once, at boot.
#
# Paths use ${DEVVY_ROOT}, which defaults to this file's parent directory's
# parent (the checkout root), so nothing here is tied to one machine. Full
# reference for every key: config/profiles.example.yaml.
#
# Editing by hand is fine. Keep one rule: a profile that allows the `guest`
# role must not set `sandbox: false` -- the registry refuses that combination
# at boot and the bot will not start.
profiles:
"""


class TemplateError(RuntimeError):
    """A template is missing, malformed, or unsafe to instantiate."""


# --- templates ----------------------------------------------------------


def available_templates(templates_dir: Path = TEMPLATES_DIR) -> List[str]:
    """Template slugs, alphabetical. A directory needs a profile.yaml to count."""
    if not templates_dir.is_dir():
        return []
    return sorted(
        d.name for d in templates_dir.iterdir() if (d / "profile.yaml").is_file()
    )


def read_template(name: str, templates_dir: Path = TEMPLATES_DIR) -> str:
    path = templates_dir / name / "profile.yaml"
    if not path.is_file():
        known = ", ".join(available_templates(templates_dir)) or "none"
        raise TemplateError(f"no such profile template: {name!r} (have: {known})")
    return path.read_text(encoding="utf-8")


# --- rendering ----------------------------------------------------------


def render_fragment(template_text: str, slug: str) -> str:
    """Substitute the target slug and indent the fragment under ``profiles:``.

    ``${DEVVY_ROOT}`` is deliberately left alone: the registry expands it at
    load time, and baking an absolute path in here is exactly the mistake that
    made the old tracked profiles.yaml useless on any other machine.
    """
    if not SLUG_RE.match(slug):
        raise TemplateError(
            f"invalid slug {slug!r}: lowercase letters, digits, '-' and '_',"
            " starting with a letter"
        )
    body = template_text.replace("@SLUG@", slug)
    if "@SLUG@" in body:  # pragma: no cover - replace() cannot leave one
        raise TemplateError(f"unsubstituted @SLUG@ left in template for {slug!r}")
    lines = [("  " + line if line.strip() else line) for line in body.splitlines()]
    return "\n".join(lines).rstrip() + "\n"


def assert_installable(fragment: str, slug: str) -> None:
    """Refuse a guest-allowed, non-sandboxed profile before it reaches disk.

    ``load_profile_registry`` enforces this too, but it enforces it at *boot*:
    writing the file first means the next restart fails instead of the command
    that caused it. A line-level check is enough here because the shape of a
    template is ours -- anything cleverer is the parser's job, at boot.
    """
    text = fragment.lower()
    guest_allowed = "guest" in text and "allowed_roles" in text
    sandbox_off = re.search(r"^\s*sandbox:\s*false\b", fragment, re.MULTILINE)
    if guest_allowed and sandbox_off:
        raise TemplateError(
            f"profile {slug!r} would allow guests with sandbox: false -- full"
            " bash network and cross-filesystem access for a guest. The"
            " registry refuses this at boot; refusing to write it now."
        )


# --- existing config ----------------------------------------------------


def installed_slugs(config_text: str) -> List[str]:
    """Slugs already present in a profiles.yaml body, in file order."""
    return [
        m.group(1)
        for line in config_text.splitlines()
        if not line.lstrip().startswith("#")
        for m in [ENTRY_SLUG_RE.match(line)]
        if m
    ]


def append_fragment(config_text: str, fragment: str) -> str:
    """Append one rendered fragment to a profiles.yaml body."""
    if not config_text.strip():
        config_text = HEADER
    body = config_text.rstrip("\n")
    return f"{body}\n\n{fragment}"


def build_config(names: Sequence[str], templates_dir: Path = TEMPLATES_DIR) -> str:
    """A whole profiles.yaml for ``names`` (template slug == target slug)."""
    text = HEADER
    for name in names:
        fragment = render_fragment(read_template(name, templates_dir), name)
        assert_installable(fragment, name)
        text = append_fragment(text, fragment)
    return text


def backup(path: Path) -> Path:
    """Copy ``path`` aside before rewriting it. Never overwrite user config."""
    target = path.with_suffix(path.suffix + f".bak-{int(time.time())}")
    target.write_text(path.read_text(encoding="utf-8"), encoding="utf-8")
    return target


# --- CLI ----------------------------------------------------------------


def _print_list(config_path: Path, templates_dir: Path) -> int:
    existing = (
        installed_slugs(config_path.read_text(encoding="utf-8"))
        if config_path.is_file()
        else []
    )
    names = available_templates(templates_dir)
    if not names:
        print(f"No profile templates under {templates_dir}", file=sys.stderr)
        return 1
    print(f"Config: {config_path}" + ("" if config_path.is_file() else "  (absent)"))
    print(f"Templates: {templates_dir}\n")
    width = max(len(n) for n in names)
    for name in names:
        state = "installed" if name in existing else "template only"
        default = " (installed by default)" if name in DEFAULT_PROFILES else ""
        print(f"  {name:<{width}}  {state}{default}")
    extra = [s for s in existing if s not in names]
    if extra:
        print("\n  In the config but not from a template: " + ", ".join(extra))
    return 0


def parse_args(argv: Optional[List[str]] = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    p.add_argument("--templates", type=Path, default=TEMPLATES_DIR)
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--list", action="store_true", help="show what is available")
    mode.add_argument(
        "--install",
        metavar="SLUGS",
        help=f"create the config with these (default: {','.join(DEFAULT_PROFILES)})",
        nargs="?",
        const=",".join(DEFAULT_PROFILES),
    )
    mode.add_argument("--add", metavar="TEMPLATE", help="append one profile")
    p.add_argument("--slug", help="target slug for --add (default: the template name)")
    p.add_argument(
        "--force",
        action="store_true",
        help="rewrite an existing config with --install (a backup is kept)",
    )
    p.add_argument("--dry-run", action="store_true", help="print, do not write")
    return p.parse_args(argv)


def _write(path: Path, text: str, *, dry_run: bool) -> None:
    if dry_run:
        print(f"--dry-run: would write {path}:\n")
        print(text)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"Wrote {path}")


def main(argv: Optional[List[str]] = None) -> int:
    args = parse_args(argv)
    config: Path = args.config
    templates: Path = args.templates

    if args.list:
        return _print_list(config, templates)

    try:
        if args.install is not None:
            names = [n.strip() for n in args.install.split(",") if n.strip()]
            if not names:
                raise TemplateError("--install needs at least one profile name")
            if config.is_file() and not args.force:
                # Re-running the installer must not silently replace a config
                # someone has since edited. Fill in what is missing instead.
                print(f"{config} exists; adding only what is missing.")
                text = config.read_text(encoding="utf-8")
                have = installed_slugs(text)
                missing = [n for n in names if n not in have]
                if not missing:
                    print(f"  already present: {', '.join(names)} -- nothing to do")
                    return 0
                for name in missing:
                    fragment = render_fragment(read_template(name, templates), name)
                    assert_installable(fragment, name)
                    text = append_fragment(text, fragment)
                    print(f"  + {name}")
                if not args.dry_run:
                    print(f"  backed up to {backup(config)}")
                _write(config, text, dry_run=args.dry_run)
                return 0
            if config.is_file() and args.force and not args.dry_run:
                print(f"Backed up existing config to {backup(config)}")
            _write(config, build_config(names, templates), dry_run=args.dry_run)
            return 0

        name = args.add
        slug = args.slug or name
        text = config.read_text(encoding="utf-8") if config.is_file() else HEADER
        if slug in installed_slugs(text):
            print(f"Profile {slug!r} is already in {config} -- nothing to do.")
            return 0
        fragment = render_fragment(read_template(name, templates), slug)
        assert_installable(fragment, slug)
        if config.is_file() and not args.dry_run:
            print(f"Backed up existing config to {backup(config)}")
        _write(config, append_fragment(text, fragment), dry_run=args.dry_run)
        if not args.dry_run:
            print(
                f"Added {slug!r}. Restart the bot to pick it up:"
                " /restart in Telegram, or sudo systemctl restart claude-bot."
            )
        return 0
    except TemplateError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    except OSError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
